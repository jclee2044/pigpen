"""Generate request types from the backend contract; no database or server required."""
from pathlib import Path
import json
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from pydantic import TypeAdapter
from pigpen.contracts import Operation, PAYLOADS

schema=TypeAdapter(Operation).json_schema()

def ts(value):
    if '$ref' in value:return value['$ref'].split('/')[-1]
    if 'const' in value:return json.dumps(value['const'])
    if 'enum' in value:return ' | '.join(json.dumps(x) for x in value['enum'])
    if 'anyOf' in value:return ' | '.join(ts(x) for x in value['anyOf'])
    kind=value.get('type')
    if kind=='array':return f'Array<{ts(value["items"])}>'
    if kind=='object':return 'Record<string, unknown>'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')

lines=['// Generated by tools/generate_api_types.py. Do not edit by hand.\n']
for name,definition in schema['$defs'].items():
    if not definition.get('properties'):
        lines.append(f'export type {name} = Record<string, never>\n')
        continue
    lines.append(f'export interface {name} {{')
    required=definition.get('required',[])
    for field,value in definition.get('properties',{}).items():
        lines.append(f'  {json.dumps(field)}{"" if field in required else "?"}: {ts(value)}')
    lines.append('}\n')
lines.append('export interface Payloads {')
for kind,model in PAYLOADS.items():lines.append(f'  {json.dumps(kind)}: {model.__name__}')
lines.append('}\n')
lines.append("export type Kind = keyof Payloads\nexport type Operation<K extends Kind = Kind> = { [P in K]: { operation_id: string; entity_id: string; actor_id: string | null; client_time: string; kind: P; data: Payloads[P] } }[K]\n")
output='\n'.join(lines)
path=ROOT/'frontend/src/api/generated.ts'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=output:raise SystemExit('Generated frontend contract is out of date')
else:path.write_text(output)
