test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
async function swipe(page:Page,item:string){
 const card=page.locator('.wish-surface').filter({hasText:item})
 await card.scrollIntoViewIfNeeded()
 const box=(await card.boundingBox())!
 const x=box.x+box.width*.8,y=box.y+box.height/2
 const session=await page.context().newCDPSession(page)
 await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
 for(let step=1;step<=8;step++)await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-120*step/8,y}]})
 await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await session.detach()
}
