 const names=await page.locator('.category-row .row-main strong').allTextContents()
 expect(names.indexOf(shared.name)).toBeLessThan(names.indexOf(personal.name))
 expect(names.indexOf('Personal child')).toBeGreaterThan(names.indexOf(shared.name))
 await page.getByRole('button',{name:'Add category',exact:true}).click()
 await page.getByRole('combobox',{name:'Category type',exact:true}).selectOption('subcategory')
 await expectPersonalLast(await page.getByLabel('Parent category',{exact:true}).locator('option').evaluateAll(options=>options.map(o=>(o as HTMLOptionElement).value).filter(Boolean)))
