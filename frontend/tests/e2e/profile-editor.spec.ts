import { test, expect } from '@playwright/test'
import { seed, command } from './helpers'

test('profile card links open a full editor; edits persist and deletion requires confirmation',async({page,request},info)=>{
 await seed(page,request,'Editor owner')
 const other=await command(request,'user.create',{name:'Editable profile'})
 await page.goto('/profiles')
 const card=page.locator('.profile-card').filter({hasText:'Editable profile'})
 const edit=card.getByRole('link',{name:'Edit Editable profile',exact:true})
 const box=await card.boundingBox(),link=await edit.boundingBox()
 expect(link!.x+link!.width).toBeGreaterThan(box!.x+box!.width-30)
 const name=await card.locator('strong').boundingBox()
 expect(Math.abs(link!.y+link!.height/2-name!.y-name!.height/2)).toBeLessThan(1)
 await expect(edit.locator('svg')).toHaveCount(1)
 await expect(edit).toHaveText('')
 expect(box!.height).toBeLessThan(120)
 await edit.click()
 await expect(page).toHaveURL(new RegExp('/profiles/'+other.id+'/edit$'))
 await expect(page.getByTestId('selected-profile')).toHaveText('Editable profile')
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.getByLabel('Display name').fill('Edited profile')
 await page.getByRole('combobox',{name:'Hat',exact:true}).selectOption('beanie')
 await page.getByRole('button',{name:'Save profile',exact:true}).click()
 await expect(page).toHaveURL(/\/profiles$/)
 await page.reload()
 await page.getByRole('link',{name:'Edit Edited profile',exact:true}).click()
 await expect(page.getByLabel('Display name')).toHaveValue('Edited profile')
 await expect(page.getByRole('combobox',{name:'Hat',exact:true})).toHaveValue('beanie')
 await page.setViewportSize({width:390,height:650})
 await page.screenshot({path:info.outputPath('editor-mobile.png'),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('button',{name:'Delete profile',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('financial history will remain')
 await page.getByRole('button',{name:'Cancel',exact:true}).click()
 expect((await (await request.get('/api/v1/records/users/'+other.id)).json()).active).toBe(true)
 await page.getByRole('button',{name:'Delete profile',exact:true}).click()
 await page.getByRole('button',{name:'Confirm delete',exact:true}).click()
 await expect(page).toHaveURL(/\/profiles$/)
 await expect(page.getByRole('link',{name:'Edit Edited profile',exact:true})).toHaveCount(0)
 expect((await (await request.get('/api/v1/records/users/'+other.id)).json()).active).toBe(false)
 await page.reload()
 await expect(page.getByRole('heading',{name:'Choose or create your profile'})).toBeVisible()
 await page.getByRole('link',{name:'Edit Editor owner',exact:true}).click()
 await expect(page.getByLabel('Display name')).toHaveValue('Editor owner')
})

test('last active profile cannot be deleted; offline editing is disabled',async({page,request,context})=>{
 const user=await seed(page,request,'Last profile')
 await page.route('**/api/v1/sync/snapshot',async route=>{
  const response=await route.fetch(),snapshot=await response.json()
  snapshot.records.users=snapshot.records.users.filter((row:{id:string})=>row.id===user.id)
  await route.fulfill({response,json:snapshot})
 })
 await page.goto('/profiles/'+user.id+'/edit')
 await expect(page.getByRole('button',{name:'Delete profile',exact:true})).toBeDisabled()
 await expect(page.getByText('Keep at least one active profile.',{exact:false})).toBeVisible()
 await expect(page.getByRole('button',{name:'Save profile',exact:true})).toBeEnabled()
 await page.waitForLoadState('networkidle')
 await context.setOffline(true)
 await expect(page.getByRole('status',{name:'',exact:true}).filter({hasText:'Offline · saved on this device'})).toBeVisible()
 await expect(page.getByRole('button',{name:'Save profile',exact:true})).toBeDisabled()
 await expect(page.getByLabel('Display name')).toBeDisabled()
})
