test('production PWA reopens offline with its original queued purchase',async({page,context,request},info)=>{
 await seed(page,request,'PWA actor')
 await page.evaluate(async()=>{await navigator.serviceWorker.ready})
 await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
 const manifest=await (await request.get('/manifest.webmanifest')).json()
 expect(manifest.display).toBe('standalone');expect(manifest.start_url).toBe('/')
 await page.setViewportSize({width:1440,height:1040});await page.goto('/')
 await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible()
 await page.screenshot({path:info.outputPath('dashboard-desktop.png'),fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:info.outputPath('dashboard-mobile.png'),fullPage:true})
 await context.setOffline(true)
 await page.reload();await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'New purchase',exact:true}).click()
 await page.getByLabel('Item or service').fill('PWA offline notebook')
 await page.getByLabel('Amount ($)',{exact:true}).fill('7.89')
 await page.getByLabel('Transaction date',{exact:true}).fill('2025-04-01')
 await page.getByRole('combobox',{name:'Category',exact:true}).selectOption({label:'Food'})
 await page.getByRole('button',{name:'Save purchase',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await expect(page.getByText('1 purchase waiting to sync.',{exact:true})).toBeVisible()
 await page.close()
 const reopened=await context.newPage();await reopened.goto('/purchases')
 await expect(reopened.getByRole('heading',{name:'Purchases',exact:true})).toBeVisible()
 await expect(reopened.getByText('1 action(s) saved on this device · Waiting to sync',{exact:true})).toBeVisible()
 expect(await reopened.evaluate(async()=>{const keys=await caches.keys();const urls=await Promise.all(keys.map(async key=>(await (await caches.open(key)).keys()).map(x=>new URL(x.url).pathname)));return urls.flat().some(x=>x.startsWith('/api/'))})).toBe(false)
 await context.setOffline(false);await reopened.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(reopened.locator('.pending-panel')).toHaveCount(0)
 await expect.poll(async()=>{const data=await (await request.get('/api/v1/purchases?month=2025-04')).json();return data.items.filter((x:{item:string})=>x.item==='PWA offline notebook').length}).toBe(1)
})

test('push permission is explicit, denial is recoverable, registration disables safely',async({page,request},info)=>{
 await page.addInitScript(()=>{
  let subscribed=sessionStorage.getItem('push-test-subscribed')==='true'
  const testState={calls:0,permission:(sessionStorage.getItem('push-test-permission')??'denied') as NotificationPermission}
  Object.assign(window,{pigpenPushTest:testState})
  Object.defineProperty(Notification,'permission',{get:()=>testState.permission})
  Object.defineProperty(Notification,'requestPermission',{value:async()=>{testState.calls++;sessionStorage.setItem('push-test-permission',testState.permission);return testState.permission}})
  const subscription={toJSON:()=>({endpoint:'https://web.push.apple.com/synthetic-test',keys:{p256dh:btoa(String.fromCharCode(4)+String.fromCharCode(0).repeat(64)).replace(/=/g,''),auth:btoa(String.fromCharCode(0).repeat(16)).replace(/=/g,'')}}),unsubscribe:async()=>{subscribed=false;sessionStorage.removeItem('push-test-subscribed');return true}}
  PushManager.prototype.getSubscription=async()=>subscribed?subscription as unknown as PushSubscription:null
  PushManager.prototype.subscribe=async()=>{subscribed=true;sessionStorage.setItem('push-test-subscribed','true');return subscription as unknown as PushSubscription}
 })
 await page.route('**/api/v1/push-config',route=>route.fulfill({json:{enabled:true,public_key:'BA'+ 'A'.repeat(85)}}))
 const actor=await seed(page,request,'Push actor')
 await page.getByRole('button',{name:'Our household',exact:true}).click()
 await page.getByRole('link',{name:'Notifications',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Notifications',exact:true})).toBeVisible()
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>Reflect.get(window,'pigpenPushTest').calls)).toBe(0)
 await page.getByRole('switch',{name:'Push notifications',exact:true}).click()
 await expect(page.getByText(/Notifications were not allowed/)).toBeVisible()
 await page.evaluate(()=>{Reflect.get(window,'pigpenPushTest').permission='granted'})
 await page.getByRole('switch',{name:'Push notifications',exact:true}).click()
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toBeEnabled()
 const device=await page.evaluate(async()=>{const db=await new Promise<IDBDatabase>(resolve=>{const r=indexedDB.open('pigpen-v1');r.onsuccess=()=>resolve(r.result)});return new Promise<string>(resolve=>{const r=db.transaction('meta').objectStore('meta').get('device');r.onsuccess=()=>resolve(r.result)})})
 let binding=await (await request.get('/api/v1/installations/'+device)).json()
 expect(binding.installation.user_id).toBe(actor.id);expect(binding.subscription.active).toBe(true)
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toHaveAttribute('aria-checked','true')
 await page.goto('/settings')
 await expect(page.getByRole('heading',{name:'Install PigPen',exact:true})).toHaveCount(0)
 await expect(page.getByText('Notifications are enabled for the selected profile.',{exact:true})).toHaveCount(0)
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toHaveAttribute('aria-checked','true')
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:info.outputPath('settings-push-enabled.png'),fullPage:true})
 await page.getByRole('switch',{name:'Push notifications',exact:true}).click()
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toBeEnabled()
 binding=await (await request.get('/api/v1/installations/'+device)).json();expect(binding.subscription.active).toBe(false)
 await expect(page.getByRole('switch',{name:'Push notifications',exact:true})).toHaveAttribute('aria-checked','false')
 await page.screenshot({path:info.outputPath('settings-push-disabled.png'),fullPage:true})
 // A push link resolves the selected recipient's inbox record after a fresh load.
 const other=await command(request,'user.create',{name:'Push sender'})
 const plan=await command(request,'request.create',{item:'Push linked plan',amount_minor:1234},other.id)
 const notes=await (await request.get('/api/v1/notifications?recipient_id='+actor.id)).json()
 await page.reload()
 await page.getByRole('button',{name:'Our household',exact:true}).click()
 await expect(page.locator('.household-dropdown .notification-count')).toBeVisible()
 const note=notes.items.find((x:{target_id:string})=>x.target_id===plan.id)
 expect(note).toBeTruthy()
 await page.goto('/notifications?notification='+note.id)
 await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.getByRole('dialog').getByText('Push linked plan',{exact:true})).toBeVisible()
})

test('new notifications show a temporary top banner while inbox stays in household menu',async({page,request},info)=>{
 const actor=await seed(page,request,'Banner recipient')
 const sender=await command(request,'user.create',{name:'Banner sender'})
 await command(request,'request.create',{item:'Existing banner request',amount_minor:100},sender.id)
 await page.reload()
 await expect(page.locator('.notification-banner')).toHaveCount(0)
 await expect(page.locator('.app-header>a[href="/notifications"]')).toHaveCount(0)
 await page.setViewportSize({width:390,height:844})
 await page.addStyleTag({content:':root{--safe-area-top:47px;--safe-area-bottom:34px}'})
 const nav=page.getByRole('navigation',{name:'Mobile navigation',exact:true})
 await expect(nav).toHaveCSS('padding-bottom','22px')
 const box=await nav.boundingBox();expect(box!.y+box!.height).toBe(844)
 const plan=await command(request,'request.create',{item:'New banner request',amount_minor:200},sender.id)
 // A real push wakes the open app, which pulls the authoritative notification.
 await page.evaluate(()=>navigator.serviceWorker.dispatchEvent(new MessageEvent('message',{data:{type:'PIGPEN_NOTIFICATION'}})))
 const banner=page.getByRole('complementary',{name:'New notification',exact:true})
 await expect(banner).toBeVisible();await expect(banner).toContainText('Banner sender submitted "New banner request" for approval')
 await expect(banner).not.toContainText('200')
 await expect.poll(async()=>(await banner.boundingBox())?.y).toBe(55)
 await page.screenshot({path:info.outputPath('notification-banner-phone.png')})
 await banner.getByRole('button',{name:'Dismiss notification'}).click()
 await expect(banner).toHaveCount(0)
 await page.evaluate(()=>navigator.serviceWorker.dispatchEvent(new MessageEvent('message',{data:{type:'PIGPEN_NOTIFICATION'}})))
 await expect(banner).toHaveCount(0)
 const notes=await (await request.get('/api/v1/notifications?recipient_id='+actor.id)).json()
 const note=notes.items.find((n:{target_id:string})=>n.target_id===plan.id)
 expect(note.read_at).toBeNull()
 await page.getByRole('button',{name:'Our household',exact:true}).click()
 await expect(page.locator('.household-dropdown').getByRole('link',{name:/Notifications/})).toBeVisible()
 await page.keyboard.press('Escape')
 await command(request,'request.create',{item:'Open from banner',amount_minor:300},sender.id)
 await page.evaluate(()=>navigator.serviceWorker.dispatchEvent(new MessageEvent('message',{data:{type:'PIGPEN_NOTIFICATION'}})))
 await expect(banner).toBeVisible()
 await banner.getByRole('link').click()
 await expect(page.getByRole('dialog').getByText('Open from banner',{exact:true})).toBeVisible()
 await expect(banner).toHaveCount(0)
 await page.keyboard.press('Escape')
 await page.clock.install()
 await command(request,'request.create',{item:'Auto-dismiss banner',amount_minor:400},sender.id)
 await page.evaluate(()=>navigator.serviceWorker.dispatchEvent(new MessageEvent('message',{data:{type:'PIGPEN_NOTIFICATION'}})))
 await expect(banner).toBeVisible()
 await page.clock.fastForward(6500)
 await expect(banner).toHaveCount(0)
})
